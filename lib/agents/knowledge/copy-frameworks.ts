export const COPY_FRAMEWORKS = `FRAMEWORKS DE AD COPY:

1. AIDA (Attention, Interest, Desire, Action)
   Estructura: Captar atención → Generar interés → Crear deseo → Llamar a la acción
   Mejor para: audiencias frías, awareness, lanzamientos
   Plataformas: Meta feed/stories, Google RSA, YouTube pre-roll

2. PAS (Problem, Agitate, Solution)
   Estructura: Identificar problema → Agitar el dolor → Presentar la solución
   Mejor para: productos que resuelven un pain-point, retargeting
   Plataformas: Meta feed, LinkedIn, Google RSA

3. BAB (Before, After, Bridge)
   Estructura: Situación actual → Situación deseada → Cómo llegar (tu producto)
   Mejor para: transformación, coaching, fitness, lifestyle
   Plataformas: Meta stories/reels, TikTok, YouTube

4. 4P (Promise, Picture, Proof, Push)
   Estructura: Prometer resultado → Pintar la imagen → Probar con evidencia → Empujar a actuar
   Mejor para: high-ticket, premium, B2B enterprise
   Plataformas: LinkedIn InMail, Google RSA

5. FAB (Features, Advantages, Benefits)
   Estructura: Características → Ventajas vs alternativas → Beneficios para el usuario
   Mejor para: productos técnicos, comparison shoppers, alto intent
   Plataformas: Google RSA (high intent), LinkedIn

6. Star-Story-Solution
   Estructura: Presentar protagonista → Contar su historia → Revelar la solución
   Mejor para: brand storytelling, UGC, conexión emocional
   Plataformas: Meta reels, TikTok, YouTube`

